private void loadPilihanLomba() {

    try {
         Connection c = Koneksi.configDB();
        Statement s = c.createStatement();

        String sql = "SELECT * FROM lomba";
        ResultSet r = s.executeQuery(sql);

        cmbLomba.removeAllItems();

        while (r.next()) {
            cmbLomba.addItem(
                r.getInt("id") + " - " + r.getString("nama_lomba")
            );
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Gagal mengambil data lomba: " + e.getMessage()
        );
    }
}

private void cekStatusSiswa() {

    try {

        Connection c = Koneksi.configDB();
        Statement s = c.createStatement();

        String sql = "SELECT status FROM pendaftaran "
                   + "WHERE user_id=" + idLoginSiswa;

        ResultSet r = s.executeQuery(sql);

        if (r.next()) {

            String status = r.getString("status");

            lblStatus.setText(
                    "*Status anda : " + status + "*"
            );

            btnDaftar.setEnabled(false);

        } else {

            lblStatus.setText(
                    "*Status anda : Belum mendaftar*"
            );

            btnDaftar.setEnabled(true);
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Gagal mengecek status: " + e.getMessage()
        );
    }
}
