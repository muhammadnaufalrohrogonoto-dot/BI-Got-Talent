    private void btnDaftarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDaftarActionPerformed
          try {

        if (cmbLomba.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Silakan pilih mata lomba terlebih dahulu!"
            );
            return;
        }

        // Mengambil pilihan dari ComboBox
        String pilihan = cmbLomba.getSelectedItem().toString();

        // Mengambil ID lomba sebelum tanda "-"
        int lombaId = Integer.parseInt(
                pilihan.split(" - ")[0]
        );

        Connection c = Koneksi.configDB();
        Statement s = c.createStatement();

        // Cek apakah siswa sudah pernah mendaftar
        String cek = "SELECT * FROM pendaftaran "
                   + "WHERE user_id=" + idLoginSiswa;

        ResultSet r = s.executeQuery(cek);

        if (r.next()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Kamu sudah melakukan pendaftaran!"
            );

            return;
        }

        // Simpan pendaftaran
        String sql = "INSERT INTO pendaftaran "
                   + "(user_id, lomba_id, status) "
                   + "VALUES ("
                   + idLoginSiswa + ", "
                   + lombaId + ", "
                   + "'Dokumen dalam Tinjauan')";

        s.executeUpdate(sql);

        JOptionPane.showMessageDialog(
                this,
                "Pendaftaran berhasil!"
        );

        lblStatus.setText(
                "*Status anda : Dokumen dalam Tinjauan*"
        );

        btnDaftar.setEnabled(false);

    } catch (HeadlessException | NumberFormatException | SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Pendaftaran gagal: " + e.getMessage()
        );
    }
   
    }//GEN-LAST:event_btnDaftarActionPerformed

